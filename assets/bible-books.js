function _bibleNorm(s) {
  return String(s == null ? "" : s).replace(/\s+/g, "");
}

// 번호(1~66) 또는 책 이름(공백·옛 표기 허용)으로 책을 찾는다. 못 찾으면 null.
function findBibleBook(key) {
  var want = _bibleNorm(key);
  if (!want) return null;
  for (var i = 0; i < BIBLE_BOOKS.length; i++) {
    var b = BIBLE_BOOKS[i];
    var hit = String(b[0]) === want || _bibleNorm(b[1]) === want;
    if (!hit && b[4]) {
      for (var j = 0; j < b[4].length; j++) {
        if (_bibleNorm(b[4][j]) === want) { hit = true; break; }
      }
    }
    if (hit) return { id: b[0], name: b[1], code: b[2], chapters: b[3] };
  }
  return null;
}

// 대한성서공회 개역개정판 읽기 주소. 책을 못 찾거나 장이 범위를 벗어나면 빈 문자열.
function bibleReadUrl(key, chapter) {
  var b = findBibleBook(key);
  var ch = parseInt(chapter, 10);
  if (!b || !ch || ch < 1 || ch > b.chapters) return "";
  return BIBLE_READ_BASE + b.code + "." + ch;
}
