function getDayIndex() {
  var now = new Date();
  var start = new Date(now.getFullYear(), 0, 0);
  var diff = now - start;
  return Math.floor(diff / 86400000);
}

function getWeekIndex() {
  var now = new Date();
  var start = new Date(now.getFullYear(), 0, 1);
  var diff = now - start;
  return Math.floor(diff / (7 * 86400000));
}

function getMonthIndex() {
  return new Date().getMonth();
}

function getVerseFor(kind) {
  var idx;
  if (kind === "daily") idx = getDayIndex();
  else if (kind === "weekly") idx = getWeekIndex();
  else idx = getMonthIndex();
  return BLESSING_POOL[idx % BLESSING_POOL.length];
}

// 이번 주의 월요일 날짜를 구한다 (월요일 00:00 기준으로 주간이 바뀌도록)
function getMondayOfWeek(date) {
  var d = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  var day = d.getDay(); // 0=일, 1=월, ... 6=토
  var diffToMonday = day === 0 ? -6 : 1 - day;
  d.setDate(d.getDate() + diffToMonday);
  return d;
}

// 방문자별로 "뽑기" — 하루는 매일 00:00, 주간은 월요일 00:00, 월간은 매달 1일 00:00에 리셋되어
// 같은 기간 안에는 뽑은 결과를 그대로 보여줌
function getPeriodKey(kind) {
  var now = new Date();
  if (kind === "daily") {
    return now.getFullYear() + "-" + (now.getMonth() + 1) + "-" + now.getDate();
  }
  if (kind === "weekly") {
    var monday = getMondayOfWeek(now);
    return monday.getFullYear() + "-" + (monday.getMonth() + 1) + "-" + monday.getDate();
  }
  return now.getFullYear() + "-" + (now.getMonth() + 1);
}

function getDrawnVerse(kind) {
  try {
    var raw = localStorage.getItem("msu_draw_" + kind);
    if (!raw) return null;
    var saved = JSON.parse(raw);
    if (saved.periodKey !== getPeriodKey(kind)) return null;
    return BLESSING_POOL[saved.index] || null;
  } catch (e) {
    return null;
  }
}

function drawRandomVerse(kind) {
  var existing = getDrawnVerse(kind);
  if (existing) return existing;
  var index = Math.floor(Math.random() * BLESSING_POOL.length);
  try {
    localStorage.setItem("msu_draw_" + kind, JSON.stringify({ periodKey: getPeriodKey(kind), index: index }));
  } catch (e) {}
  return BLESSING_POOL[index];
}

// localStorage는 기기(브라우저)마다 따로 저장되기 때문에, 로그인한 계정이라면 서버(verse_draws)에
// 뽑은 결과를 저장해서 모바일/데스크탑 등 어떤 기기로 봐도 같은 결과가 나오게 한다.
// 비로그인 방문자는 계정이 없으니 기존처럼 localStorage 결과를 그대로 쓴다.
function getDrawnVerseAsync(kind) {
  if (typeof getSession !== "function") return Promise.resolve(getDrawnVerse(kind));
  return getSession().then(function (session) {
    if (!session) return getDrawnVerse(kind);
    var client = getClient();
    return client.from("verse_draws")
      .select("verse_index")
      .eq("user_id", session.user.id)
      .eq("kind", kind)
      .eq("period_key", getPeriodKey(kind))
      .then(function (res) {
        var row = res.data && res.data[0];
        return row ? (BLESSING_POOL[row.verse_index] || null) : null;
      });
  }).catch(function () {
    return getDrawnVerse(kind);
  });
}

function drawRandomVerseAsync(kind) {
  if (typeof getSession !== "function") return Promise.resolve(drawRandomVerse(kind));
  return getSession().then(function (session) {
    if (!session) return drawRandomVerse(kind);
    var client = getClient();
    return client.rpc("draw_blessing_verse", {
      p_kind: kind, p_period_key: getPeriodKey(kind), p_pool_size: BLESSING_POOL.length
    }).then(function (res) {
      if (res.error || res.data === null || res.data === undefined) return drawRandomVerse(kind);
      return BLESSING_POOL[res.data] || drawRandomVerse(kind);
    });
  }).catch(function () {
    return drawRandomVerse(kind);
  });
}

