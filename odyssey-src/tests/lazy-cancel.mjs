import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=d3d11','--enable-gpu'] });
const page = await browser.newPage(); await page.setViewport({ width: 480, height: 820 });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error' && !/favicon/.test(m.text())) errors.push(m.text()); });
const cdp = await page.target().createCDPSession(); await cdp.send('Network.enable'); await cdp.send('Network.setCacheDisabled', { cacheDisabled: true });
await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 80, downloadThroughput: 1024 * 1024, uploadThroughput: 256 * 1024 });
await page.goto('http://localhost:8765/index.html?reset&notype&zone=egypt');
await page.waitForFunction('window.__ready === true', { timeout: 180000 });
await new Promise(r => setTimeout(r, 3000));
console.log('떠나기 직전 대기 인원', await page.evaluate(() => window.__debug.pendingNPC));
await page.evaluate(() => { const D = window.__debug; D.travelTo(D.markers.find(m => m.data.id === 'to-midian2').data); });
await page.waitForFunction('window.__debug.zone === "midian"', { timeout: 120000 });
await new Promise(r => setTimeout(r, 20000));
console.log('미디안 도착 후 20초:', await page.evaluate(() => { const D = window.__debug; return 'NPC ' + D.markers.filter(m => m.data.model).map(m => m.data.id).join(',') + ' | 애굽 사람 섞임 ' + D.markers.filter(m => m.data.lazy).length + ' | 대기 ' + D.pendingNPC; }));
await page.evaluate(() => { const D = window.__debug; D.travelTo(D.markers.find(m => m.data.to === 'egypt').data); });
await page.waitForFunction('window.__debug.zone === "egypt"', { timeout: 120000 });
await page.waitForFunction('window.__debug.pendingNPC === 0', { timeout: 60000 });
console.log('애굽 다시 입장: 마을 사람', await page.evaluate(() => window.__debug.markers.filter(m => m.data.lazy && !m.hidden).length), '명 표시');
console.log('errors', errors.length ? errors.join('\n') : 'none');
await browser.close();
