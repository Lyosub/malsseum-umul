import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=d3d11','--enable-gpu'] });
const page = await browser.newPage(); await page.setViewport({ width: 800, height: 560 });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
let bytes = 0; const files = [];
page.on('response', async r => { if (r.status() >= 400) console.log('404:', r.url()); try { const b = await r.buffer(); bytes += b.length; files.push(r.url().split('/').slice(3).join('/')); } catch (e) {} });
const t0 = Date.now();
await page.goto('http://localhost:8765/index.html?reset');
await page.waitForFunction('window.__ready === true', { timeout: 90000 });
console.log('사이트 빌드: 알파마을 준비', Date.now() - t0, 'ms, 받은 양', (bytes / 1048576).toFixed(2), 'MB,', files.length, '개 파일');
const before = bytes;
await page.evaluate(() => window.__debug.player.position.set(0, 0, -4));
await new Promise(r => setTimeout(r, 4000));
console.log('포털 근처에서 미디안 미리 받기:', ((bytes - before) / 1048576).toFixed(2), 'MB');
await page.evaluate(() => window.__debug.player.position.set(0, 0, -17));
await new Promise(r => setTimeout(r, 600));
const b2 = bytes, t1 = Date.now();
await page.click('#interact-btn');
await page.waitForFunction('window.__debug.zone==="midian"', { timeout: 60000 });
console.log('미디안 이동', Date.now() - t1, 'ms, 이동 중 추가로 받은 양', ((bytes - b2) / 1048576).toFixed(2), 'MB');
console.log('errors', errors.length ? errors.join('\n') : 'none');
await browser.close();
