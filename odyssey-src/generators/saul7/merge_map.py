import sys
P = sys.argv[1]
t = open(P, encoding='utf-8').read()
start = t.index('### 7 「사울과 함께」 — 삼상 8–15')
end = t.index('🏛 물매와 돌 다섯 · 📜 다윗', start) + len('🏛 물매와 돌 다섯 · 📜 다윗')
new = '''### 7 「사울과 다윗」 — 삼상 8–31 ★ 2026-10-30 범위 확정 (예전 7 「사울과 함께」 + 8 「소년 다윗」을 한 편으로 합침, 이후 번호 하나씩 당김)
장별 상세는 `In Odyssey 7편 사울과 다윗 — 상세 기획 (초안).md`.
- 1부 사울 왕: 1. 우리에게 왕을 주어 (8장) · 2. 암나귀를 찾다가 (9–10장) 🎮 잃은 나귀 찾기 · 3. ⚔ 야베스 길르앗을 구함 (11장) · 4. 기도하기를 쉬는 죄 (12장)
- 2부 버림받은 왕: 5. 이레를 기다렸으나 (13장) · 6. ⚔ **요나단과 무기 든 소년** (14장) 🎮 절벽 오르기 · 7. ⚔ 순종이 제사보다 낫고 (15장)
- 3부 소년 다윗: 8. 사람은 외모를 보거니와 (16:1–13) 🧒 · 9. 수금 타는 다윗 (16:14–23) 🎮 리듬 · 10. ⚔ **골리앗** — "전쟁은 여호와께 속한 것인즉"(17:47) 🎮 갑옷 벗기 → 돌 다섯 → 물매 · 11. 요나단과의 언약 (18–20장) 🎮 창 피하기·화살 신호
- 4부 쫓기는 다윗: 12. 놉의 떡과 아둘람 굴 (21–23장) · 13. 기름 부음 받은 자를 치지 않음 (24·26장) 🎮 진영 잠입 · 14. 아비가일 (25장) 👩 · 15. ⚔ 시글락을 되찾음 (27·29–30장) · 16. 🔸⚔ 길보아 산, 그리고 야베스 (28·31장, 엔돌은 본문 보기만, 사울의 죽음은 원문 해설로 분명히)
- 시편 23편은 곁-2 「시편과 지혜」로 옮김.
🏛 물매와 돌 다섯 · 📜 다윗'''
t = t[:start] + new + t[end:]
t = t.replace('2(민 1–9) · 3', '2(민 1–10) · 3')
t = t.replace('| 사무엘상 | 6 · 7 · 7 |', '| 사무엘상 | 6 · 7 |')
t = t.replace('| 시편 | 7 · 8 · 곁-2 |', '| 시편 | 8 · 곁-2 |')
t = t.replace('(7편 소년 다윗을 마치면 연다)', '(7편 「사울과 다윗」을 마치면 연다)')
t = t.replace('| 7 소년 다윗 |', '| 7 사울과 다윗 |')
open(P, 'w', encoding='utf-8').write(t)
print('ok')
